    <h1>Sobre Nós</h1>
    <h3>Tudo começou com uma ideia simples: tornar o cuidado com a saúde mais fácil e organizado. Muitas pessoas, especialmente idosos e seus cuidadores, enfrentam dificuldades para lembrar os horários dos medicamentos, acompanhar prescrições e manter uma rotina segura.

        Pensando nisso, nasceu este sistema. Nosso objetivo é oferecer uma ferramenta prática que ajude no gerenciamento de medicamentos, permitindo cadastrar pacientes, cuidadores, prescrições e horários de forma simples e intuitiva.

        Acreditamos que a tecnologia pode ser uma grande aliada no cuidado com a saúde. Por isso, buscamos desenvolver um ambiente confiável, acessível e fácil de usar, contribuindo para que pacientes e familiares tenham mais tranquilidade no dia a dia.

        Mais do que um sistema, este projeto representa o compromisso de utilizar a tecnologia para promover organização, segurança e qualidade de vida, ajudando as pessoas a cuidarem melhor de quem mais importa.
    </h3>
